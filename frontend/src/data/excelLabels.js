// Every language's label for a key -- used to read a header row whatever
// language the file was downloaded in.
export const getAllExcelLabels = (key) =>
  Array.from(new Set(Object.values(EXCEL_LABELS).map((labels) => labels[key]).filter(Boolean)));

// employee_gender.gender / sexe values ("Homme", "male", "M", ...).
export const translateGender = (value, labels) => {
  const g = String(value || '').trim().toLowerCase();
  if (['homme', 'male', 'm'].includes(g)) return labels.male;
  if (['femme', 'female', 'f'].includes(g)) return labels.female;
  return value || '';
};

export const translateStatus = (value, labels) => {
  const s = String(value || '').trim().toLowerCase();
  if (s === 'actif' || s === 'active') return labels.active;
  if (s === 'archive' || s === 'archivé' || s === 'archived') return labels.archived;
  return value || '';
};
